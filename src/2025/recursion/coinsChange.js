// Напишите функцию, которая считает, сколькими способами можно разменять
// заданную сумму денег money, имея в распоряжении монетки номиналами coins.

// Например, если нам нужно разменять 4 рубля монетками [1, 2], то есть три
// способа: 1+1+1+1, 1+1+2 и 2+2.

// В этой задаче необходимо посчитать количество способов.


console.log(countChange(4, [1, 2])); // 3 1+1+1+1, 1+1+2 и 2+2
console.log(countChange(10, [5, 2, 3])); // 4

// Всего способов=(Способы, если взяли монету)+(Способы, если не взяли монету)
// N(money,coins)=N(money−coins[0],coins)+N(money,coinsrest)

// Первый сценарий предполагает, что вы берете первую монету из списка.
// В этом случае ваша целевая сумма уменьшается на номинал этой монеты,
// но список монет остается прежним, так как по условию задачи количество монет
// каждого номинала не ограничено и вы можете взять такую же монету снова.

// Второй сценарий предполагает, что вы не используете этот номинал
// (ни сейчас, ни в будущем для этого варианта размена).
// В этом случае целевая сумма остается неизменной, но вы переходите
// к решению той же задачи с усеченным списком монет, из которого удален первый номинал.

function countChange(money, coins) {
  // --- БАЗОВЫЕ СЛУЧАИ (Условия выхода) ---

  // 1. Если деньги стали равны 0, значит мы успешно разменяли сумму.
  // Возвращаем 1 (это один найденный способ).
  if (money === 0) {
    return 1;
  }

  // 2. Если деньги ушли в минус (взяли слишком большую монету).
  // Это тупик. Возвращаем 0 способов.
  if (money < 0) {
    return 0;
  }

  // 3. Если монеты закончились, а деньги всё ещё остались (money > 0).
  // Разменять невозможно. Возвращаем 0 способов.
  if (coins.length === 0) {
    return 0;
  }

  // --- РЕКУРСИВНЫЙ ШАГ ---

  // Сценарий 1: Берем первую монету.
  // Мы вычитаем её из суммы, но список монет оставляем тем же (coins),
  // потому что можем взять эту монету ещё раз.
  // Важно: мы передаем в функцию новое значение, НЕ меняя переменную money здесь.
  const waysWithCoin = countChange(money - coins[0], coins); // 3, [1, 2], 2, [1, 2], 1, [2, 2], 0, [1, 2]

  // Сценарий 2: Выкидываем первую монету.
  // Мы оставляем сумму прежней (money), но урезаем список монет (coins.slice(1)),
  // как бы говоря "с этим номиналом мы закончили, пробуем остальные".
  const waysWithoutCoin = countChange(money, coins.slice(1));

  // Итоговый результат — это сумма способов из обоих сценариев.
  return waysWithCoin + waysWithoutCoin;
}


// Вот пошаговая хронология выполнения (Call Stack). Мы идем в глубину: сначала всегда пытаемся взять монету (левая ветка), а когда упираемся в тупик или успех — возвращаемся и пропускаем монету (правая ветка).
// Задача: собрать сумму
// [ 4 ] монетами
