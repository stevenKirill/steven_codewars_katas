// Это главный вызов. Он хочет узнать сумму вариантов от двух детей:
// (А) Взять 1: countChange(3, [1, 2])
// (Б) Убрать 1: countChange(4, [2])
// 2. countChange(3, [1, 2]) (Ветка А от шага 1)
// Сумма уменьшилась. Снова делимся:
// (А) Взять 1: countChange(2, [1, 2])
// (Б) Убрать 1: countChange(3, [2])
// 3. countChange(2, [1, 2]) (Ветка А от шага 2)
// Сумма еще уменьшилась. Делимся:
// (А) Взять 1: countChange(1, [1, 2])
// (Б) Убрать 1: countChange(2, [2])
// 4. countChange(1, [1, 2]) (Ветка А от шага 3)
// (А) Взять 1: countChange(0, [1, 2])
// (Б) Убрать 1: countChange(1, [2])
// 5. countChange(0, [1, 2]) (Ветка А от шага 4)
// УСПЕХ! Сумма равна
// [ 0 ].
// Возвращаем 1. (Мы нашли путь: 1+1+1+1).
// 6. countChange(1, [2]) (Ветка Б от шага 4 — мы вернулись назад)
// Мы пытаемся собрать сумму 1 только двойками.
// (А) Взять 2: countChange(-1, [2]) -> Возвращает 0 (перебор).
// (Б) Убрать 2: countChange(1, []) -> Возвращает 0 (нет монет).
// Итог шага 6: Возвращаем 0.
// Итог шага 4: (1 от успеха) + (0 от неудачи) = 1. Возвращаемся в шаг 3.
// 7. countChange(2, [2]) (Ветка Б от шага 3 — тот самый момент «магии»)
// Мы вернулись к состоянию, где у нас уже есть две единицы (сумма была 4, стала 2), и мы решили больше не брать единицы.
// (А) Взять 2: countChange(0, [2])
// (Б) Убрать 2: countChange(2, [])
// 8. countChange(0, [2]) (Ветка А от шага 7)
// УСПЕХ! Сумма равна
// [ 0 ].
// Возвращаем 1. (Мы нашли путь: 1+1+2).
// 9. countChange(2, []) (Ветка Б от шага 7)
// Возвращаем 0 (монеты кончились).
// Итог шага 7: 1 + 0 = 1.
// Итог шага 3: (1 от пути 1+1+1+1) + (1 от пути 1+1+2) = 2. Возвращаемся в шаг 2.
// 10. countChange(3, [2]) (Ветка Б от шага 2)
// Мы вернулись очень высоко. У нас есть одна единица (4-1=3), и мы отказались брать единицы дальше. Пытаемся собрать 3 двойками.
// (А) Взять 2: countChange(1, [2]) -> (внутри будет неудача, вернет 0).
// (Б) Убрать 2: countChange(3, []) -> (неудача, вернет 0).
// Итог шага 10: Возвращаем 0.
// Итог шага 2: 2 + 0 = 2. Возвращаемся в самое начало (шаг 1).
// 11. countChange(4, [2]) (Ветка Б от шага 1)
// Мы в самом начале отказались от единиц вообще. Пытаемся собрать 4 только двойками.
// (А) Взять 2: countChange(2, [2])
// (Б) Убрать 2: countChange(4, [])
// 12. countChange(2, [2]) (Ветка А от шага 11)
// (А) Взять 2: countChange(0, [2])
// (Б) Убрать 2: countChange(2, [])
// 13. countChange(0, [2]) (Ветка А от шага 12)
// УСПЕХ! Сумма равна
// [ 0 ].
// Возвращаем 1. (Мы нашли путь: 2+2).
// 14. countChange(2, []) (Ветка Б от шага 12)
// Возвращаем 0.
// Итог шага 12: 1 + 0 = 1.
// 15. countChange(4, []) (Ветка Б от шага 11)
// Возвращаем 0.
// Итог шага 11: 1 + 0 = 1.
// ФИНАЛ (Итог шага 1)
