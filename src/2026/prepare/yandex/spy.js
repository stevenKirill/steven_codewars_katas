// По линии Первого главного управления получена оперативная сводка: разведчик, работающий в глубоком тылу, передаёт шифротелеграммы чрезвычайной важности. Спецслужбы противника ведут беспрецедентную охоту за нашими каналами связи. Единственный доступный канал передачи данных ненадёжен — сообщение проходит через цепочку конспиративных ретрансляторов, и на каждом узле часть символов случайным образом искажается и заменяется на *.

// Вы — шифровальщик Центра, прикреплённый к этому оперативному делу. Обстановка требует предельной собранности. Оперативник может повторить передачу, однако каждый лишний сеанс связи повышает вероятность запеленгования и провала всей резидентуры. Приказ руководства: за минимальное число сеансов связи восстановить полный текст шифротелеграммы, собрав читаемые символы из каждого перехвата. Провал недопустим, товарищ — на кону результаты многолетней оперативной разработки. На вас возложена высокая ответственность за безопасность государства. Исполнение этого задания — ваш священный долг перед Родиной.

// Условие:
// Для связи с оперативником используйте fetch. Адрес канала связи доступен из константы API_URL. Ответ приходит в формате JSON следующей структуры:

// {
//     "data": "some_string"
// }
// Необходимо использовать fetch, чтобы с минимальным количеством запросов получить полную шифротелеграмму.

// Ваша функция должна вернуть строку, состоящую только из допустимых символов: ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789

// Пример:

// function solution() {
//     fetch(API_URL).json(); // "K**",
//     fetch(API_URL).json(); // "*G*",
//     fetch(API_URL).json(); // "**B",

//     return "KGB";
// }

async function solution() {
  let result = null;

  // Цикл выполняется до тех пор, пока результат не инициализирован
  // или в нём остаётся хотя бы одна звёздочка
  while (result === null || result.includes("*")) {
    // Делаем запрос к API
    const response = await fetch(API_URL);
    const json = await response.json();
    const currentData = json.data;

    // Если это первый запрос, превращаем строку в массив символов
    if (result === null) {
      result = currentData.split("");
      continue;
    }

    // Заполняем пропущенные символы из нового перехвата
    for (let i = 0; i < result.length; i++) {
      if (result[i] === "*" && currentData[i] !== "*") {
        result[i] = currentData[i];
      }
    }
  }

  // Собираем массив обратно в строку и возвращаем Центру
  return result.join("");
}

module.exports = solution;
