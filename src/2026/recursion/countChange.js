// Напишите функцию, которая определяет варианты, как можно разменять заданную сумму
// денег money, имея в распоряжении монетки номиналами coins.

// Например, если нам нужно разменять 4 рубля монетками [1, 2],
// то есть три способа: 1+1+1+1, 1+1+2 и 2+2.

// Необходимо вернуть массив строк с вариантами.

function countChange(money, coins) {
  const results = [];

  // Сортировка монет не обязательна для нахождения сумм,
  // но помогает упорядочить вывод и немного оптимизировать перебор.
  coins.sort((a, b) => a - b);

  function findCombinations(remainingMoney, startIndex, currentPath) {
    // Базовый случай: если сумма собрана (остаток 0), сохраняем путь
    if (remainingMoney === 0) {
      results.push(currentPath.join("+"));
      return;
    }

    // Если остаток отрицательный, этот путь тупиковый
    if (remainingMoney < 0) {
      return;
    }

    // Перебираем монеты, начиная с текущего индекса (startIndex),
    // чтобы избежать дубликатов (например, 1+2 и 2+1)
    for (let i = startIndex; i < coins.length; i++) {
      const coin = coins[i];

      // Оптимизация: так как массив отсортирован, если текущая монета
      // больше остатка, то и последующие тоже будут больше. Можно прерывать цикл.
      if (coin > remainingMoney) break;

      currentPath.push(coin); // Добавляем монету

      console.log(currentPath)

      // Рекурсивный вызов: вычитаем монету из суммы.
      // Передаем 'i', а не 'i + 1', так как одну монету можно использовать повторно.
      findCombinations(remainingMoney - coin, i, currentPath);

      currentPath.pop(); // Удаляем монету (backtracking), чтобы попробовать следующую
    }
  }

  findCombinations(money, 0, []);
  return results;
}

